CREATE TABLE shared_snippets (
    id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    -- Short, URL-safe, and drawn from an alphabet with look-alike characters
    -- removed, so a link survives being read aloud or retyped.
    short_id         VARCHAR(12) NOT NULL UNIQUE,
    -- SHA-256 of language + code. Unique, so re-sharing identical code returns
    -- the existing link instead of creating another row.
    code_hash        VARCHAR(64) NOT NULL UNIQUE,
    language         VARCHAR(30) NOT NULL,
    code             TEXT NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_accessed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE  shared_snippets IS 'Publicly readable code snippets addressed by short link.';
COMMENT ON COLUMN shared_snippets.code_hash IS 'Deduplication key; identical code reuses the existing short link.';
COMMENT ON COLUMN shared_snippets.last_accessed_at IS 'Retention signal. Not updated on every read — that would make a public GET a write.';

-- short_id and code_hash are already indexed by their UNIQUE constraints.
CREATE INDEX idx_shared_snippets_last_accessed ON shared_snippets (last_accessed_at);


-- ============================================================================
-- SECTION 7 — Payments
--
-- Donations only; nothing here gates access to content.
-- ============================================================================

CREATE TABLE donation_orders (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    -- Gateway order identifier. Unique, so a repeated verification callback or
    -- webhook delivery settles the same order rather than duplicating it.
    order_id    VARCHAR(100) NOT NULL UNIQUE,
    payment_id  VARCHAR(100),
    signature   VARCHAR(255),
    -- Whole currency units, not minor units. Converted to paise at the gateway
    -- boundary, and the captured amount is reconciled against this on webhook.
    amount      INTEGER NOT NULL CONSTRAINT ck_donation_amount CHECK (amount > 0),
    currency    VARCHAR(10) NOT NULL DEFAULT 'INR',
    status      VARCHAR(30) NOT NULL DEFAULT 'CREATED'
                CONSTRAINT ck_donation_status
                    CHECK (status IN ('CREATED', 'COMPLETED', 'FAILED')),
    donor_name  VARCHAR(255),
    donor_email VARCHAR(255),
    message     TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE  donation_orders IS 'Voluntary contributions. COMPLETED is terminal and never downgraded.';
COMMENT ON COLUMN donation_orders.amount IS 'Whole currency units. Reconciled against the gateway-captured amount before settling.';
COMMENT ON COLUMN donation_orders.signature IS 'Gateway signature retained for audit after successful verification.';

-- order_id is already indexed by its UNIQUE constraint.
CREATE INDEX idx_donation_orders_status ON donation_orders (status);


