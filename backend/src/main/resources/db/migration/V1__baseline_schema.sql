    CONSTRAINT uq_daily_user_date UNIQUE (user_id, activity_date)
);

COMMENT ON TABLE  user_learning_daily_activity IS 'Daily rollup driving the streak calendar and weekly leaderboard.';
COMMENT ON COLUMN user_learning_daily_activity.activity_date IS 'Local date in the learner''s configured zone.';
COMMENT ON COLUMN user_learning_daily_activity.qualifying_event_count IS 'Actions that count towards keeping a streak alive.';

CREATE INDEX idx_daily_activity_user_date ON user_learning_daily_activity (user_id, activity_date DESC);


-- ============================================================================
-- SECTION 4 — DSA sheet
--
-- A structured problem sheet as a module of its own, a sibling of the course
-- catalogue rather than a special case of it: nothing here references paths,
